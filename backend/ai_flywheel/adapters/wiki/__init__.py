"""The Wiki gate: the contract a mounted Wiki imposes on what may be written.

Six collaborators, one contract:

- `schema` — the mounted Wiki's `.wiki-schema.md`: how to read it, which path segments
  no write may touch.
- `validator` — the write-time check of one document against that contract.
- `router` — where a knowledge document belongs: the declared route, validated by evidence.
- `t5_adapter` — the generic draft rewritten into the Wiki's own practice-card shape.
- `postflight` — what the Wiki's own scripts say about the written document.
- `gate` — `WikiGate`, the object the rest of the product talks to.

`ai_flywheel.adapters.wiki_gate` re-exports everything here.
"""
