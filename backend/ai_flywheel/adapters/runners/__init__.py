"""The runner layer: where a batch's review and write plan come from.

Six collaborators, one contract:

- `contracts` — the wire format: where a plan or review came from, why a reply was
  refused, and the shared text helpers.
- `normalizers` — one planner item → one deterministic write (or a drop with a reason).
- `outcomes` — one runner reply → a plan or a review, or a refusal that fails the node.
- `prompts` — the P02 and P03 prompts.
- `heuristic` — the local dry-run planner.
- `clients` — the CLI and API runners, plus `resolve_runner_mode` / `build_runner`.

Every name the former `ai_flywheel.adapters.runners` module exported is re-exported here,
so existing imports keep working unchanged.
"""
